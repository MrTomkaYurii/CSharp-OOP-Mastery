// Приклад показує "прихований" бік роботи з інтерфейсами: метод Array.Sort()
// вміє сортувати масив будь-якого типу лише тому, що елементи (тут int)
// реалізують стандартний інтерфейс IComparable (вбудований у .NET для типу int).
// Сам виклик Array.Sort всередині порівнює елементи саме через цей інтерфейс,
// не знаючи наперед, що це int — це готує до наступного прикладу (p393),
// де IComparable реалізовується вручну для власного класу.
using System;

class Program
{
    static void Main(string[] args)
    {
        var myInt = new[] { 20, 4, 16, 9, 2 };    // Створюємо масив цілих чисел.

        Array.Sort(myInt);                      // Сортуємо елементи за величиною (через IComparable<int>).

        foreach (var i in myInt)                // Виводимо відсортовані значення.
            Console.Write($"{i} ");
    }
}
