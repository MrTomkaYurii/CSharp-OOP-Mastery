// Найпростіший приклад використання інтерфейсу в C#.
// Демонструється базова ідея: інтерфейс IIfc1 лише оголошує контракт
// (метод PrintOut без реалізації), а клас MyClass бере на себе
// зобов'язання цей контракт реалізувати.
// Задача прикладу - показати, що клас, який реалізує інтерфейс,
// зобов'язаний надати тіло для кожного методу, оголошеного в інтерфейсі.
using System;

interface IIfc1                        // Оголошення інтерфейсу: лише сигнатура методу, без реалізації.
{
    void PrintOut(string s);
}

class MyClass : IIfc1                  // Клас реалізує інтерфейс IIfc1.
{
    public void PrintOut(string s)    // Реалізація методу інтерфейсу (обов'язково public).
    {
        Console.WriteLine($"Calling through: {s}");
    }
}

class Program
{
    static void Main()
    {
        MyClass mc = new MyClass(); // Створення екземпляра класу.
        mc.PrintOut("object"); // Виклик методу напряму через тип класу.
    }
}