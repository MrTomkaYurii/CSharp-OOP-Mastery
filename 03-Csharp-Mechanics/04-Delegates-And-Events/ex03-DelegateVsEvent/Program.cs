using System;

// ============================================================================
// КАСТОМНИЙ ПРИКЛАД 3: Чому потрібен 'event', якщо вже є багатоадресні делегати?
// ============================================================================
// НАВІЩО ЦЕЙ ПРИКЛАД:
// Розв'язати головну плутанину: "У багатоадресний делегат ми вже могли додавати
// методи через '+='. Навіщо мова C# створила окреме ключове слово 'event'?".
//
// ГОЛОВНА ВІДПОВІДЬ:
// ІНКАПСУЛЯЦІЯ ТА ЗАХИСТ ВІД ЗЛОВМИСНОГО АБО ПОМИЛКОВОГО ВТРУЧАННЯ.
// ============================================================================

namespace ex03_DelegateVsEvent;

// ============================================================================
// [КРОК 1] НЕБЕЗПЕЧНИЙ КЛАС: відкритий делегат (БЕЗ слова event)
// ============================================================================
class UnsafeSensor
{
    // Відкрите поле делегата. Будь-хто ззовні має повний доступ!
    public Action<int>? TemperatureAlert;

    public void Measure(int currentTemp)
    {
        if (currentTemp > 75)
        {
            Console.WriteLine($"[UnsafeSensor] Температура критична: {currentTemp}°C! Оповіщаємо...");
            TemperatureAlert?.Invoke(currentTemp);
        }
    }
}

// ============================================================================
// [КРОК 2] БЕЗПЕЧНИЙ КЛАС: подія (З ключовим словом event)
// ============================================================================
class SafeSensor
{
    // Ключове слово 'event' обмежує зовнішній доступ: тільки += та -=!
    public event Action<int>? TemperatureAlert;

    public void Measure(int currentTemp)
    {
        if (currentTemp > 75)
        {
            Console.WriteLine($"[SafeSensor] Температура критична: {currentTemp}°C! Оповіщаємо...");
            TemperatureAlert?.Invoke(currentTemp);
        }
    }
}

class Program
{
    static void Main()
    {
        Console.OutputEncoding = System.Text.Encoding.UTF8;
        Console.WriteLine("=== Приклад 3: Делегат vs Подія (Інкапсуляція та захист) ===\n");

        // ====================================================================
        // [КРОК 3] ДЕМОНСТРАЦІЯ 3 ПРОБЛЕМ ВІДКРИТОГО ДЕЛЕГАТА:
        // ====================================================================
        Console.ForegroundColor = ConsoleColor.Red;
        Console.WriteLine("--- ЧАСТИНА 1: Тестування НЕБЕЗПЕЧНОГО делегата ---");
        Console.ResetColor();

        UnsafeSensor unsafeSensor = new();

        // Підписник 1: Пожежна служба
        unsafeSensor.TemperatureAlert += temp => Console.WriteLine($"   🔥 [Пожежна служба] Сигнал тривоги: {temp}°C!");

        // ДИВЕРСІЯ 1: Випадкове перезаписування через '=' замість '+='
        // Програміст помилився і написав '='. Пожежна служба стерлася зі списку!
        unsafeSensor.TemperatureAlert = temp => Console.WriteLine($"   ❄️ [Кондиціонер] Увімкнути охолодження на {temp}°C.");

        // ДИВЕРСІЯ 2: Фальшивий виклик ззовні!
        // Сенсор не фіксував високої температури, але сторонній код може викликати сповіщення:
        Console.WriteLine("   -> Сторонній код примусово викликає unsafeSensor.TemperatureAlert(100):");
        unsafeSensor.TemperatureAlert(100);

        // ДИВЕРСІЯ 3: Обнулення списку
        // unsafeSensor.TemperatureAlert = null; // Повністю вимикає сповіщення для всіх!
        Console.WriteLine();

        // ====================================================================
        // [КРОК 4] ЯК КЛЮЧОВЕ СЛОВО 'event' ЗАХИЩАЄ СИСТЕМУ:
        // ====================================================================
        Console.ForegroundColor = ConsoleColor.Green;
        Console.WriteLine("--- ЧАСТИНА 2: Тестування БЕЗПЕЧНОЇ події (event) ---");
        Console.ResetColor();

        SafeSensor safeSensor = new();

        // Обидва підписники реєструються коректно через '+='
        safeSensor.TemperatureAlert += temp => Console.WriteLine($"   🔥 [Пожежна служба] Сигнал тривоги: {temp}°C!");
        safeSensor.TemperatureAlert += temp => Console.WriteLine($"   ❄️ [Кондиціонер] Увімкнути охолодження на {temp}°C.");

        // СПРОБА ПОРУШИТИ БЕЗПЕКУ (Компілятор C# блокує помилки!):
        // --------------------------------------------------------------------
        // safeSensor.TemperatureAlert = ...; // ПОМИЛКА: Не можна присвоювати через '='! Тільки '+=' або '-='
        // safeSensor.TemperatureAlert = null;// ПОМИЛКА: Не можна скинути чужих підписників!
        // safeSensor.TemperatureAlert(100);  // ПОМИЛКА: Не можна викликати подію ззовні класу!
        // --------------------------------------------------------------------

        // Єдиний законний шлях — викликати метод самого сенсора:
        Console.WriteLine("   -> Викликаємо штатний метод сенсора Measure(85):");
        safeSensor.Measure(85);

        // ====================================================================
        // [КРОК 5] ГОЛОВНИЙ ПІДСУМОК ДЛЯ СТУДЕНТІВ:
        // ====================================================================
        // 'event' — це мовний захист навколо делегата.
        // Ззовні класу дозволено ТІЛЬКИ:
        //   '+=' (підписатися)
        //   '-=' (відписатися)
        // А керувати викликом події може ТІЛЬКИ сам об'єкт, у якому вона оголошена!
        // ====================================================================
    }
}
