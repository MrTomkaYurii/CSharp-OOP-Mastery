using System;

// ============================================================================
// ПРИКЛАД: p369[SOLIS] - Еволюція від анонімних методів до лямбда-виразів
// ============================================================================
// Тема: Як мова C# еволюціонувала в записі коротких функцій,
//       та як поступово спрощувався синтаксис лямбда-виразів.
// ============================================================================

// Делегат приймає int і повертає double
delegate double MyDel(int par);

class Program
{
    static void Main()
    {
        // КРОК 1: Класичний анонімний метод (C# 2.0).
        // Вимагає ключового слова 'delegate', явного вказування типу параметра та блоку { return ...; }
        MyDel del = delegate (int x) { return x + 1; };

        // КРОК 2: Базова лямбда-функція (введена в C# 3.0).
        // Замість слова 'delegate' з'явився оператор лямбди '=>' (читається як "прямує до" або "переходить у").
        // Тип параметра (int x) все ще вказується явно, тіло у фігурних дужках.
        MyDel le1 = (int x) => { return x + 1; };

        // КРОК 3: Виведення типів (Type Inference).
        // Компілятор уже знає сигнатуру MyDel(int par), тому тип 'int' можна не писати.
        MyDel le2 = (x) => { return x + 1; };

        // КРОК 4: Опущення круглих дужок.
        // Якщо параметр РІВНО ОДИН, круглі дужки навколо нього можна опустити.
        // (Якщо параметрів 0 або більше 1, дужки обов'язкові: () => ... або (a, b) => ...).
        MyDel le3 = x => { return x + 1; };

        // КРОК 5: Лямбда-вираз (Expression-bodied lambda).
        // Якщо тіло складається лише з одного оператора return, фігурні дужки { } 
        // та ключове слово 'return' можна повністю прибрати!
        // Результат виразу після '=>' автоматично повертається.
        MyDel le4 = x => x + 1;

        // Всі п'ять варіантів створюють абсолютно еквівалентний код та повертають однаковий результат (13):
        Console.WriteLine($"{del(12)}");
        Console.WriteLine($"{le1(12)}");
        Console.WriteLine($"{le2(12)}");
        Console.WriteLine($"{le3(12)}");
        Console.WriteLine($"{le4(12)}");
    }
}