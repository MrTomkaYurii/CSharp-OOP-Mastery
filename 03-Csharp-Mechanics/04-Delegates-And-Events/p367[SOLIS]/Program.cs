using System;

// ============================================================================
// ПРИКЛАД: p367[SOLIS] - Анонімні методи та замикання (Closures)
// ============================================================================
// Тема: Визначення методу безпосередньо за місцем використання без окремого імені,
//       а також захоплення локальних змінних (Captured Variables / Closure).
// ============================================================================

// Оголошуємо тип делегата без параметрів і без повернення значення
delegate void MyDel();

class Program
{
    static void Main()
    {
        MyDel mDel;

        // Внутрішній блок коду (створює власну область видимості)
        {
            int x = 5; // Локальна змінна, яка існує тільки всередині цих фігурних дужок { }

            // АНОНІМНИЙ МЕТОД (введений у C# 2.0):
            // Замість створення окремого іменованого методу в класі,
            // ми визначаємо тіло методу прямо тут через ключове слово 'delegate'.
            //
            // ЗАМИКАННЯ (CLOSURE):
            // Анонімний метод використовує зовнішню локальну змінну 'x'.
            // Це називається "захопленням змінної" (variable capture).
            // Компілятор C# під капотом створює спеціальний прихований клас,
            // куди переносить змінну 'x' у купу (heap), тому вона НЕ знищується
            // при виході з блоку видимості!
            mDel = delegate
            {
                Console.WriteLine("Value of x: {0}", x);
            };
        } // Тут закінчується область видимості локальної змінної x

        // Якщо розкоментувати рядок нижче, код не скомпілюється:
        // поза межами свого блоку змінна 'x' більше недоступна напряму!
        // Console.WriteLine("Value of x: {0}", x);

        // Перевіряємо та викликаємо делегат:
        // Хоча блок коду завершився, делегат mDel все ще зберігає доступ до захопленої змінної x = 5!
        if (null != mDel)
            mDel(); // Виведе: Value of x: 5
    }
}
