using System;

// ============================================================================
// ПРИКЛАД: p361[SOLIS] - Багатоадресні делегати зі значенням, що повертається
// ============================================================================
// Тема: Що відбувається, коли делегат повертає значення (тип int), 
//       але містить у списку викликів кілька методів?
// ============================================================================

// Оголошуємо тип делегата, який повертає значення int і не приймає параметрів
delegate int MyDel();

class MyClass
{
    int IntValue = 5;

    public int Add2() { IntValue += 2; return IntValue; }
    public int Add3() { IntValue += 3; return IntValue; }
}

class Program
{
    static void Main()
    {
        MyClass mc = new MyClass();

        // Ініціалізуємо делегат першим методом Add2
        MyDel mDel = mc.Add2;

        // Додаємо ще два методи через оператор '+='
        mDel += mc.Add3;
        mDel += mc.Add2;

        // ВАЖЛИВИЙ НЮАНС C#:
        // Делегат mDel містить 3 виклики: mc.Add2 -> mc.Add3 -> mc.Add2.
        // При виклику mDel() виконуються ВСІ три методи по черзі:
        //  1) Add2(): IntValue стає 5 + 2 = 7 (повертає 7)
        //  2) Add3(): IntValue стає 7 + 3 = 10 (повертає 10)
        //  3) Add2(): IntValue стає 10 + 2 = 12 (повертає 12)
        //
        // ПРОТЕ делегат повертає значення ТІЛЬКИ ОСТАННЬОГО викликаного методу в списку!
        // Результати попередніх методів (7 і 10) ігноруються і губляться.
        // Тому в консоль буде виведено: Value: 12
        //
        // ПОРАДА ДЛЯ ПОЧАТКІВЦІВ:
        // Зазвичай багатоадресні делегати використовують для методів, що повертають void.
        // Якщо ж вам потрібні результати всіх методів, слід викликати mDel.GetInvocationList()
        // та проходитися циклом по кожному делегату окремо.
        Console.WriteLine($"Value: {mDel()}");
    }
}