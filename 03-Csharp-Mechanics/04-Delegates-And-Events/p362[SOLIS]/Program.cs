using System;

// ============================================================================
// ПРИКЛАД: p362[SOLIS] - Багатоадресні делегати з параметрами за посиланням (ref)
// ============================================================================
// Тема: Як поводяться параметри ref у ланцюжку викликів багатоадресного делегата.
// ============================================================================

// Оголошуємо тип делегата з параметром за посиланням (ref)
delegate void MyDel(ref int X);

class MyClass
{
    public void Add2(ref int x) { x += 2; }
    public void Add3(ref int x) { x += 3; }

    static void Main()
    {
        MyClass mc = new MyClass();

        // Створюємо багатоадресний делегат із трьох методів: Add2, Add3, Add2
        MyDel mDel = mc.Add2;
        mDel += mc.Add3;
        mDel += mc.Add2;

        int x = 5;

        // ПОВЕДІНКА ПАРАМЕТРА REF У БАГАТОАДРЕСНОМУ ДЕЛЕГАТІ:
        // Оскільки параметр передається за посиланням (ref), методи в ланцюжку
        // працюють з однією і тією ж коміркою пам'яті по черзі:
        //  1) Початкове значення: x = 5
        //  2) Викликається перший метод mc.Add2(ref x) -> x стає 5 + 2 = 7
        //  3) Викликається другий метод mc.Add3(ref x) -> отримує вже 7 -> x стає 7 + 3 = 10
        //  4) Викликається третій метод mc.Add2(ref x) -> отримує вже 10 -> x стає 10 + 2 = 12
        //
        // Таким чином, кожен наступний метод бачить зміни, внесені попереднім!
        mDel(ref x);

        // Буде виведено: Value: 12
        Console.WriteLine($"Value: {x}");
    }
}