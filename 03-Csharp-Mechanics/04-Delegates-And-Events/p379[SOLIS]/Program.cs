using System;

// ============================================================================
// ПРИКЛАД: p379[SOLIS] - Вступ до подій (Events) у C#
// ============================================================================
// Тема: Що таке подія, ключове слово 'event', концепція "Видавець-Підписник"
//       (Publisher-Subscriber) та слабке зв'язування компонентів (Loose Coupling).
// ============================================================================

// Оголошуємо тип делегата, який буде сигнатурою нашої події
delegate void Handler();

// 1. ВИДАВЕЦЬ (PUBLISHER):
// Клас, у якому виникає певна дія (стан). Він володіє подією та ініціює її виклик.
class Incrementer
{
    // Ключове слово 'event' перед делегатом:
    // Подія — це захищена обгортка навколо делегата. Вона обмежує зовнішній світ:
    // ззовні дозволено тільки підписуватися (+ =) або відписуватися (- =).
    // Ніхто ззовні не може випадково обнулити подію (= null) або викликати її напряму!
    public event Handler CountedADozen;

    public void DoCount()
    {
        for (int i = 1; i < 100; i++)
        {
            // Коли лічильник доходить до числа, кратного 12 (дюжина):
            // Перевіряємо, чи підписався хоч хтось на подію (CountedADozen != null)
            // і "вистрілюємо" (генеруємо / публікуємо) подію.
            if (i % 12 == 0 && CountedADozen != null)
                CountedADozen();
        }
    }
}

// 2. ПІДПИСНИК (SUBSCRIBER):
// Клас, який "слухає" подію та реагує на неї за допомогою методу-обробника.
class Dozens
{
    // Лічильник зафіксованих дюжин
    public int DozensCount { get; private set; }

    public Dozens(Incrementer incrementer)
    {
        DozensCount = 0;

        // ПІДПИСКА НА ПОДІЮ:
        // Реєструємо наш метод IncrementDozensCount в списку підписників події.
        // Зверніть увагу: ми використовуємо оператор '+='
        incrementer.CountedADozen += IncrementDozensCount;
    }

    // МЕТОД-ОБРОБНИК (Event Handler):
    // Його сигнатура обов'язково повинна збігатися з делегатом Handler (void, без параметрів).
    // Він буде автоматично викликаний щоразу, коли видавець генерує подію.
    void IncrementDozensCount()
    {
        DozensCount++;
    }
}

class Program
{
    static void Main()
    {
        // Створюємо видавця
        Incrementer incrementer = new Incrementer();

        // Створюємо підписника (він підписується на incrementer у своєму конструкторі)
        Dozens dozensCounter = new Dozens(incrementer);

        // Запускаємо процес підрахунку у видавця.
        // Incrementer виконує цикл і нічого не знає про те, хто такий DozensCounter,
        // але успішно викликає підписаний обробник щоразу при 12, 24, 36...
        incrementer.DoCount();

        // Виводимо підсумковий результат підписника (у діапазоні 1..99 є 8 дюжин)
        Console.WriteLine("Number of dozens = {0}", dozensCounter.DozensCount);
    }
}