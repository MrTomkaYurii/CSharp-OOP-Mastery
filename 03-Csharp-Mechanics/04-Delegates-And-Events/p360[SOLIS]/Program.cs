using System;

// ============================================================================
// ПРИКЛАД: p360[SOLIS] - Багатоадресні делегати (Multicast Delegates)
// ============================================================================
// Тема: Об'єднання декількох методів в один делегат через оператор '+=',
//       прив'язка методів екземпляра та статичних методів, перевірка на null.
// ============================================================================

// Оголошуємо тип делегата без параметрів та без повернення значення (void)
delegate void PrintFunction();

class Test
{
    // Метод екземпляра (non-static) — потребує наявності об'єкта класу Test
    public void Print1()
    {
        Console.WriteLine("Print1 -- instance");
    }

    // Статичний метод (static) — викликається через ім'я класу Test.Print2
    public static void Print2()
    {
        Console.WriteLine("Print2 -- static");
    }
}

class Program
{
    static void Main()
    {
        Test t = new Test();       // Створюємо екземпляр класу Test
        PrintFunction pf;          // Оголошуємо змінну делегата (за замовчуванням null)

        // 1. Прив'язка першого методу екземпляра (скорочений синтаксис замість new PrintFunction(t.Print1)):
        pf = t.Print1;

        // 2. БАГАТОАДРЕСНІСТЬ (MULTICAST):
        // За допомогою оператора '+=' додаємо додаткові методи до списку викликів (Invocation List).
        // До делегата можна додавати як статичні методи, так і методи конкретних об'єктів.
        // Більше того, один і той самий метод можна додати декілька разів!
        pf += Test.Print2; // Додаємо статичний метод
        pf += t.Print1;    // Додаємо метод екземпляра повторно
        pf += Test.Print2; // Додаємо статичний метод повторно

        // Зараз список викликів делегата pf містить 4 посилання:
        // [1] t.Print1 -> [2] Test.Print2 -> [3] t.Print1 -> [4] Test.Print2

        // 3. ПЕРЕВІРКА НА NULL ПЕРЕД ВИКЛИКОМ:
        // Якщо делегат порожній (дорівнює null), виклик pf() викличе виняток NullReferenceException.
        // Тому обов'язково перевіряємо, чи є в делегаті хоча б один зареєстрований метод.
        // (Примітка: у сучасному C# замість if (null != pf) зазвичай пишуть: pf?.Invoke();)
        if (null != pf)
            pf();                   // Викликаємо всі методи по черзі у порядку їх додавання
        else
            Console.WriteLine("Delegate is empty");
    }
}
