using System;
using System.Collections.Generic;

// ============================================================================
// КАСТОМНИЙ ПРИКЛАД 1: Делегат як параметр методу (Callback / Стратегія)
// ============================================================================
// НАВІЩО ЦЕЙ ПРИКЛАД:
// Пояснити студенту: "НАВІЩО взагалі потрібен делегат?".
//
// ГОЛОВНА ІДЕЯ:
// Делегат дозволяє передавати ПОВЕДІНКУ (метод) як аргумент в інший метод!
// Це дозволяє написати один універсальний алгоритм (наприклад, фільтрацію),
// а конкретне правило поведінки передавати ззовні.
// ============================================================================

namespace ex01_DelegateAsParameter;

// ============================================================================
// [КРОК 1] ОГОЛОШУЄМО ТИП ДЕЛЕГАТА-КОНТРАКТУ:
// ============================================================================
// Будь-який метод, що приймає int і повертає bool (умова виконується / ні)
delegate bool NumberFilter(int number);

class Program
{
    // ========================================================================
    // [КРОК 2] УНІВЕРСАЛЬНИЙ МЕТОД ФІЛЬТРАЦІЇ:
    // ========================================================================
    // Він не знає наперед, за яким правилом фільтруватимуться числа.
    // Замість цього він делегує перевірку кожного числа переданому делегату 'filter'.
    static List<int> Filter(List<int> sourceList, NumberFilter filter)
    {
        List<int> result = new();

        foreach (int number in sourceList)
        {
            // [ІНВОКАЦІЯ / ВИКЛИК]:
            // filter(number) фактично викликає той метод, який нам передали!
            if (filter(number))
            {
                result.Add(number);
            }
        }

        return result;
    }

    // ========================================================================
    // [КРОК 3] КОНКРЕТНІ МЕТОДИ-ПРАВИЛА (Кандидати для передачі в делегат):
    // ========================================================================
    // Зверніть увагу: їхня сигнатура точно відповідає NumberFilter (int -> bool)
    static bool IsEven(int number) => number % 2 == 0;
    static bool IsPositive(int number) => number > 0;

    // ========================================================================
    // [КРОК 4] ГОЛОВНИЙ ФЛОУ В MAIN (Покроковий показ для викладача):
    // ========================================================================
    static void Main()
    {
        Console.OutputEncoding = System.Text.Encoding.UTF8;
        Console.WriteLine("=== Приклад 1: Делегат як параметр методу ===\n");

        List<int> numbers = new() { -15, -4, 0, 3, 8, 12, 25, 42, 77, 90, 105 };
        PrintNumbers("Початковий список чисел:", numbers);

        // --------------------------------------------------------------------
        // ЕТАП 1: Явне створення об'єкта делегата (як у книзі Соліса p349)
        // --------------------------------------------------------------------
        // Студенти бачать чіткий зв'язок: назву методу IsEven кладемо в new NumberFilter(...)
        NumberFilter filterDel = new NumberFilter(IsEven);
        List<int> evenNumbers = Filter(numbers, filterDel);
        PrintNumbers("1. Парні числа (явний екземпляр new NumberFilter(IsEven)):", evenNumbers);

        // --------------------------------------------------------------------
        // ЕТАП 2: Скорочене неявне зв'язування (Method Group Conversion)
        // --------------------------------------------------------------------
        // Передаємо просто ім'я IsPositive без дужок ().
        // Компілятор C# САМ підставляє: new NumberFilter(IsPositive)!
        List<int> positiveNumbers = Filter(numbers, IsPositive);
        PrintNumbers("2. Додатні числа (автоматичне зв'язування з IsPositive):", positiveNumbers);

        // --------------------------------------------------------------------
        // ЕТАП 3: Анонімний метод на місці (C# 2.0)
        // --------------------------------------------------------------------
        // Якщо правило потрібне лише раз, окремий метод можна не виносити.
        List<int> multiplesOfFive = Filter(numbers, delegate (int n)
        {
            return n != 0 && n % 5 == 0;
        });
        PrintNumbers("3. Числа, кратні 5 (анонімний метод delegate { ... }):", multiplesOfFive);

        // --------------------------------------------------------------------
        // ЕТАП 4: Сучасний лямбда-вираз (C# 3.0+)
        // --------------------------------------------------------------------
        // Найкоротший і найвиразніший запис у сучасному коді:
        List<int> greaterThanFifty = Filter(numbers, n => n > 50);
        PrintNumbers("4. Числа більші за 50 (лямбда n => n > 50):", greaterThanFifty);

        List<int> negativeNumbers = Filter(numbers, n => n < 0);
        PrintNumbers("5. Від'ємні числа (лямбда n => n < 0):", negativeNumbers);

        // --------------------------------------------------------------------
        // ПІДСУМОК ДЛЯ СТУДЕНТІВ:
        // Метод Filter написаний ОДИН РАЗ і ніколи більше не переписується!
        // Будь-яке нове правило фільтрації додається ззовні.
        // Це реалізація принципу ООП Open/Closed (відкритий для розширення).
        // --------------------------------------------------------------------
    }

    static void PrintNumbers(string title, List<int> list)
    {
        Console.WriteLine(title);
        Console.WriteLine(string.Join(", ", list));
        Console.WriteLine();
    }
}
