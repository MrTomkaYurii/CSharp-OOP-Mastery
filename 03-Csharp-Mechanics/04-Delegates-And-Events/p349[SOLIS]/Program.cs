// Тема: Оголошення типу делегата, створення змінної делегата, 
//       прив'язка методу та виконання виклику.
// ============================================================================

// 1. ОГОЛОШЕННЯ ТИПУ ДЕЛЕГАТА:
// Делегат — це тип даних, який зберігає посилання на метод із певною сигнатурою.
// У даному випадку 'MyDel' може вказувати на будь-який метод, який:
//  - повертає void (нічого не повертає)
//  - приймає один аргумент типу int
delegate void MyDel(int value);

class Program
{
    // Метод, сигнатура якого відповідає делегату MyDel (void, int)
    void PrintLow(int value)
    {
        Console.WriteLine($"{value} - Low Value");
    }

    // Ще один метод із такою ж сигнатурою (void, int)
    void PrintHigh(int value)
    {
        Console.WriteLine($"{value} - High Value");
    }

    static void Main()
    {
        Program program = new Program();

        // 2. ОГОЛОШЕННЯ ЗМІННОЇ ДЕЛЕГАТА:
        // Змінна 'del' зараз має значення null (ще ні на що не вказує)
        MyDel del;

        // Генерація випадкового числа від 0 до 98
        Random rand = new Random();
        int randomValue = rand.Next(99);

        // 3. ІНІЦІАЛІЗАЦІЯ ДЕЛЕГАТА (ПРИВ'ЯЗКА МЕТОДУ):
        // Залежно від умови, делегату призначається або PrintLow, або PrintHigh.
        // Зверніть увагу: передається назва методу як посилання, без круглих дужок ()!
        // Синтаксис 'new MyDel(...)' — це явне створення екземпляра делегата.
        // (У сучасному C# також можна писати просто: del = randomValue < 50 ? program.PrintLow : program.PrintHigh;)
        del = randomValue < 50
                 ? new MyDel(program.PrintLow)
                 : new MyDel(program.PrintHigh);

        // можна також використовувати тернарний оператор без явного створення екземпляра делегата:
        // del = randomValue < 50
        //        ? program.PrintLow
        //        : program.PrintHigh;

        // 4. ВИКЛИК ДЕЛЕГАТА:
        // Виклик делегата синтаксично виглядає як виклик звичайного методу.
        // При цьому фактично викликається метод, посилання на який зараз лежить у 'del'.
        del(randomValue);
    }
}