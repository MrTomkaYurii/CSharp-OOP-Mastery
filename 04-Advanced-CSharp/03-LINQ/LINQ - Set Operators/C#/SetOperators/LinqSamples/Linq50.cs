using System;
using System.Linq;

namespace SetOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор Intersect (Перетин двох множин)
    // ==============================================================================================
    // Категорія: Set Operators (Оператори над множинами)
    // Призначення: Повертає тільки ті унікальні елементи, які одночасно присутні в ОБОХ послідовностях (A ∩ B).
    //
    // Принцип роботи:
    //   - Створює множину елементів другої колекції.
    //   - Перебирає елементи першої колекції: якщо елемент знайдено в другій множині, він повертається
    //     і видаляється з множини (щоб уникнути дублікатів у результаті).
    //
    // Тип виконання:
    //   - Відкладене виконання (Deferred Execution, Streaming).
    // ==============================================================================================

    public partial class LinqSamplesSetOperators
    {
        /// <summary>
        /// Приклад 50: Використання оператора Intersect для знаходження спільних чисел у двох масивах.
        /// </summary>
        public void Linq50()
        {
            int[] numbersA = { 0, 2, 4, 5, 6, 8, 9 };
            int[] numbersB = { 1, 3, 5, 7, 8 };

            #region LINQ Method Syntax (Intersect)

            // Спільними для обох масивів є числа 5 та 8
            var commonNumbers = numbersA.Intersect(numbersB);

            Console.WriteLine("Спільні числа, що зустрічаються в обох масивах:");
            foreach (var n in commonNumbers)
            {
                Console.WriteLine(n);
            }

            #endregion
        }
    }
}
