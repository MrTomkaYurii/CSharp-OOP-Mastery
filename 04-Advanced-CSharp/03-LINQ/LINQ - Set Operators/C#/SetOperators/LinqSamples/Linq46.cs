using System;
using System.Linq;

namespace SetOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор Distinct (Усунення дублікатів у множині)
    // ==============================================================================================
    // Категорія: Set Operators (Оператори над множинами)
    // Призначення: Видаляє повторювані елементи з послідовності, повертаючи тільки унікальні значення.
    //
    // Принцип роботи:
    //   - Внутрішньо використовує структуру даних HashSet<T> (Set-семантика).
    //   - Під час ітерації кожен елемент перевіряється на наявність у множині:
    //     * якщо елемент новий — він повертається і додається до хеш-таблиці;
    //     * якщо вже зустрічався — пропускається.
    //   - Для порівняння використовується EqualityComparer<T>.Default (або переданий IEqualityComparer<T>).
    //
    // Тип виконання:
    //   - Відкладене виконання (Deferred Execution, Streaming): елементи повертаються по одному,
    //     але внутрішня хеш-таблиця зростає в міру обходу.
    // ==============================================================================================

    public partial class LinqSamplesSetOperators
    {
        /// <summary>
        /// Приклад 46: Використання оператора Distinct для отримання унікальних простих множників числа 300.
        /// </summary>
        public void Linq46()
        {
            // Масив простих множників числа 300 (2 * 2 * 3 * 5 * 5), містить дублікати
            int[] factorsOf300 = { 2, 2, 3, 5, 5 };

            #region LINQ Method Syntax (Distinct)

            // Залишаємо лише унікальні множники: { 2, 3, 5 }
            var uniqueFactors = factorsOf300.Distinct();

            Console.WriteLine("Унікальні прості множники числа 300:");
            foreach (var f in uniqueFactors)
            {
                Console.WriteLine(f);
            }

            #endregion
        }
    }
}
