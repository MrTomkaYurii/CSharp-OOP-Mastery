using System;
using System.Linq;

namespace PartitioningOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор Skip (Секціонування / Пропуск перших N елементів)
    // ==============================================================================================
    // Категорія: Partitioning Operators (Оператори розбиття / пагінації)
    // Призначення: Пропускає вказану кількість суміжних елементів із початку послідовності та повертає
    //              всі інші елементи, що залишилися.
    //
    // Принцип роботи:
    //   - Skip(count) ігнорує перші count елементів, після чого транслює всі наступні.
    //   - Якщо count <= 0, повертається вся вхідна послідовність.
    //   - Якщо count більше кількості елементів у послідовності, повертається порожня послідовність.
    //   - Комбінація Skip(pageIndex * pageSize).Take(pageSize) є класичним патерном постраничної розбивки (Paging).
    //
    // Тип виконання:
    //   - Відкладене виконання (Deferred Execution, Streaming).
    // ==============================================================================================

    public partial class LinqSamplesPartitioningOperators
    {
        /// <summary>
        /// Приклад 22: Використання оператора Skip для пропуску перших 4 елементів масиву.
        /// </summary>
        public void Linq22()
        {
            // Вхідні дані: масив чисел
            int[] numbers = { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 };

            #region LINQ Method Syntax (Skip)

            // Пропускаємо перші 4 числа та повертаємо всі наступні
            var allButFirst4Numbers = numbers.Skip(4);

            Console.WriteLine("Усі елементи, крім перших 4:");
            foreach (var n in allButFirst4Numbers)
            {
                Console.WriteLine(n);
            }

            #endregion
        }
    }
}
