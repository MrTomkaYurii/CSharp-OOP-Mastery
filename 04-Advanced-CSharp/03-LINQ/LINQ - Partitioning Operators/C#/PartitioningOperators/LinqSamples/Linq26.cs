using System;
using System.Linq;

namespace PartitioningOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор SkipWhile (Умовний пропуск з початку)
    // ==============================================================================================
    // Категорія: Partitioning Operators (Оператори розбиття / секціонування)
    // Призначення: Пропускає елементи з початку послідовності доти, доки заданий предикат повертає true,
    //              і повертає ВСІ наступні елементи, починаючи з першого, де умова стала false.
    //
    // Принцип роботи та відмінність від Where:
    //   - SkipWhile пропускає елементи, ПОКИ умова істинна.
    //   - Як тільки зустрічається ПЕРШИЙ елемент, де предикат повертає false, перевірка умови
    //     ПРИПИНЯЄТЬСЯ НАЗАВЖДИ, і ВСІ залишкоStylві елементи повертаються «як є» (навіть якщо вони знову
    //     задовольняють початкову умову).
    //
    // Тип виконання:
    //   - Відкладене виконання (Deferred Execution, Streaming).
    // ==============================================================================================

    public partial class LinqSamplesPartitioningOperators
    {
        /// <summary>
        /// Приклад 26: Пропуск елементів із початку, доки не зустрінеться перше число, що ділиться на 3 (n % 3 == 0).
        /// Повертає це число та всі наступні елементи масиву.
        /// </summary>
        public void Linq26()
        {
            // Масив: { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 }
            // Умова пропуску: n % 3 != 0 (число НЕ ділиться на 3)
            // 5 % 3 != 0 (пропуск), 4 % 3 != 0 (пропуск), 1 % 3 != 0 (пропуск).
            // 3 % 3 == 0 (умова false -> зупинка пропуску! Починаючи з 3 повертаються ВСІ елементи).
            int[] numbers = { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 };

            #region LINQ Method Syntax (SkipWhile)

            var allButFirst3Numbers = numbers.SkipWhile(n => n % 3 != 0);

            Console.WriteLine("Усі елементи, починаючи з першого кратного 3:");
            foreach (var n in allButFirst3Numbers)
            {
                Console.WriteLine(n);
            }

            #endregion
        }
    }
}
