using System;
using System.Linq;

namespace PartitioningOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор Take (Секціонування / Вибірка перших N елементів)
    // ==============================================================================================
    // Категорія: Partitioning Operators (Оператори розбиття / пагінації)
    // Призначення: Повертає вказану кількість суміжних елементів із початку послідовності.
    //
    // Принцип роботи:
    //   - Take(count) відраховує count елементів, повертає їх і відразу завершує перебір.
    //   - Якщо count <= 0, повертається порожня послідовність.
    //   - Якщо в послідовності менше ніж count елементів, повертаються всі наявні без винятків.
    //
    // Тип виконання:
    //   - Відкладене виконання (Deferred Execution, Streaming, Short-circuiting).
    // ==============================================================================================

    public partial class LinqSamplesPartitioningOperators
    {
        /// <summary>
        /// Приклад 20: Використання оператора Take для отримання тільки перших 3 елементів масиву.
        /// </summary>
        public void Linq20()
        {
            // Вхідні дані: числовий масив
            int[] numbers = { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 };

            #region LINQ Method Syntax (Take)

            // Отримуємо перші 3 числа
            var first3Numbers = numbers.Take(3);

            Console.WriteLine("Перші 3 числа з масиву:");
            foreach (var n in first3Numbers)
            {
                Console.WriteLine(n);
            }

            #endregion
        }
    }
}
