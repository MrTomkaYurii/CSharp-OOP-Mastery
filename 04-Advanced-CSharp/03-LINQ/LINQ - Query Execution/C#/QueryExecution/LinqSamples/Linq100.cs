using System;
using System.Linq;

namespace QueryExecution
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Негайне виконання (Immediate Execution)
    // ==============================================================================================
    // Категорія: Query Execution (Механізми виконання запитів)
    // Призначення: Демонстрація примусової матеріалізації запиту в пам'ять (in-memory snapshot).
    //
    // Принцип роботи:
    //   - Виклик методів матеріалізації (ToList, ToArray, ToDictionary) або скалярних агрегатів
    //     (Count, Sum, Max, Min, First) примушує LINQ негайно виконати весь запит.
    //   - Усі побічні ефекти (інкремент ++i) відбуваються в момент виклику методу матеріалізації.
    //   - Наступні проходи циклом foreach уже читають збережені в пам'яті дані зі списку List<T>,
    //     а не виконують логіку запиту повторно.
    //
    // Тип виконання:
    //   - Негайне виконання (Immediate Execution).
    // ==============================================================================================

    public partial class LinqSamplesQueryExecution
    {
        /// <summary>
        /// Приклад 100: Демонстрація негайного виконання за допомогою ToList(); змінна i інкрементується відразу.
        /// </summary>
        public void Linq100()
        {
            // Методи матеріалізації викликають негайне виконання запиту
            int[] numbers = new int[] { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 };

            int i = 0;
            var immediateQuery = (
                from num in numbers
                select ++i)
                .ToList();

            // Змінна i вже була збільшена 10 разів під час виклику ToList():
            Console.WriteLine("The current value of i is {0}", i); // i дорівнює 10

            // Перебір готового матеріалізованого списку вже не змінює змінну i:
            foreach (var item in immediateQuery)
            {
                Console.WriteLine("v = {0}, i = {1}", item, i);
            }
        }
    }
}
