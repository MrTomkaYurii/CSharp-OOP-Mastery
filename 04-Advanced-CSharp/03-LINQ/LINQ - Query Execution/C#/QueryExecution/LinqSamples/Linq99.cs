using LinqSamplesCommon.Model;
using System;
using System.Collections.Generic;
using System.Linq;

namespace QueryExecution
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Відкладене виконання (Deferred Execution)
    // ==============================================================================================
    // Категорія: Query Execution (Механізми виконання запитів)
    // Призначення: Демонстрація лінивої природи LINQ — створення запиту НЕ виконує його обчислення.
    //
    // Принцип роботи:
    //   - Оголошення LINQ-запиту лише формує план виконання (об'єкт ітератора, що реалізує IEnumerable<T>).
    //   - Обчислення коду (включно з побічними ефектами, наприклад, інкрементом ++i) починається ТІЛЬКИ тоді,
    //     коли послідовність починає безпосередньо ітеруватися (виклик GetEnumerator() / MoveNext() у foreach).
    //   - Елементи обробляються "на вимогу" (по одному за крок), а не всі одразу.
    //
    // Тип виконання:
    //   - Відкладене виконання (Deferred Execution).
    // ==============================================================================================

    public partial class LinqSamplesQueryExecution
    {
        /// <summary>
        /// Приклад 99: Демонстрація відкладеного виконання; змінна i не змінюється до початку циклу foreach.
        /// </summary>
        public void Linq99()
        {
            // Запит не виконується при його оголошенні
            int[] numbers = new int[] { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 };

            int i = 0;
            var simpleQuery =
                from num in numbers
                select ++i;

            // Локальна змінна 'i' НЕ збільшується на етапі створення запиту:
            Console.WriteLine("The current value of i is {0}", i); // i все ще дорівнює 0

            // Виконання запиту відбувається покроково під час ітерації foreach:
            foreach (var item in simpleQuery)
            {
                Console.WriteLine("v = {0}, i = {1}", item, i); // тепер i інкрементується на кожному кроці
            }
        }
    }
}
