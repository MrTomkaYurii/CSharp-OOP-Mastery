using System;
using System.Linq;

namespace GenerationOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Статичний метод Enumerable.Repeat (Повторення елемента)
    // ==============================================================================================
    // Категорія: Generation Operators (Оператори генерації послідовностей)
    // Призначення: Генерує послідовність, яка містить одне й те саме значення задану кількість разів.
    //
    // Принцип роботи:
    //   - Приймає значення типу T (елемент для повторення) та count (кількість повторень).
    //   - Працює ліниво (on-demand): при кожному зверненні ітератора повертає те саме значення count разів.
    //   - Не створює масивів у пам'яті, що робить його високоефективним O(1) за пам'яттю.
    //   - Викидає ArgumentOutOfRangeException, якщо count < 0.
    //
    // Тип виконання:
    //   - Відкладене виконання (Deferred Execution, Streaming).
    // ==============================================================================================

    public partial class LinqSamplesGenerationOperators
    {
        /// <summary>
        /// Приклад 66: Генерація послідовності, яка містить число 7 рівно десять разів за допомогою Repeat.
        /// </summary>
        public void Linq66()
        {
            // Генеруємо 10 повторень числа 7
            var numbers = Enumerable.Repeat(7, 10);
            
            Console.WriteLine("101 Linq examples - no changes.");
            foreach (var n in numbers)
            {
                Console.WriteLine(n);
            }
        }
    }
}
