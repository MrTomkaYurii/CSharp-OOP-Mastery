using System;
using System.Linq;

namespace Quantifiers
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор All (Квантор загальності)
    // ==============================================================================================
    // Категорія: Quantifiers (Оператори-квантори)
    // Призначення: Перевіряє, чи задовольняють УСІ елементи послідовності заданий предикат.
    //
    // Принцип роботи:
    //   - Повертає bool: true, якщо абсолютно кожен елемент задовольняє умову, і false — якщо хоча б один не задовольняє.
    //   - Підтримує швидкий вихід (short-circuiting): як тільки знайдено перший елемент, що НЕ відповідає умові,
    //     перебір негайно припиняється і повертається false.
    //   - Для порожньої послідовності за математичним визначенням квантора повертає true ("vacuous truth").
    //
    // Тип виконання:
    //   - Негайне виконання (Immediate Execution).
    // ==============================================================================================

    public partial class LinqSamplesQuantifiers
    {
        /// <summary>
        /// Приклад 70: Використання All для перевірки, чи містить масив виключно непарні числа.
        /// </summary>
        public void Linq70()
        {
            int[] numbers = { 1, 11, 3, 19, 41, 65, 19 };

            // Перевіряємо, чи всі числа є непарними (n % 2 == 1)
            bool onlyOdd = numbers.All(n => n % 2 == 1);

            Console.WriteLine("The list contains only odd numbers: {0}", onlyOdd);
        }
    }
}
