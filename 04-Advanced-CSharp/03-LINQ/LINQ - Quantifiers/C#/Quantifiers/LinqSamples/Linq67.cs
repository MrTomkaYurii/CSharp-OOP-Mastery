using System;
using System.Linq;

namespace Quantifiers
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор Any (Квантор існування)
    // ==============================================================================================
    // Категорія: Quantifiers (Оператори-квантори)
    // Призначення: Перевіряє, чи містить колекція хоча б один елемент (без параметрів),
    //              або чи задовольняє хоча б один елемент заданий предикат (з параметром).
    //
    // Принцип роботи:
    //   - Повертає булеве значення bool (true або false).
    //   - Підтримує швидкий вихід (short-circuiting): як тільки знайдено перший елемент,
    //     що відповідає умові, перебір негайно зупиняється і повертається true.
    //   - Для порожньої колекції завжди повертає false.
    //   - Більш ефективний за numbers.Count() > 0, оскільки не рахує всі елементи, а перевіряє лише наявність.
    //
    // Тип виконання:
    //   - Негайне виконання (Immediate Execution).
    // ==============================================================================================

    public partial class LinqSamplesQuantifiers
    {
        /// <summary>
        /// Приклад 67: Використання Any для перевірки, чи містить хоча б одне слово підрядок 'ei'.
        /// </summary>
        public void Linq67()
        {
            string[] words = { "believe", "relief", "receipt", "field" };

            // Перевіряємо, чи є в масиві бодай одне слово з підрядком "ei"
            bool iAfterE = words.Any(w => w.Contains("ei"));

            Console.WriteLine("There is a word in the list that contains 'ei': {0}", iAfterE);
        }
    }
}
