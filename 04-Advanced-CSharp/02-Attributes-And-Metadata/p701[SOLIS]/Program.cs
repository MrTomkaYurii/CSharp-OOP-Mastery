using System;

/// <summary>
/// =========================================================================================
/// СИСТЕМНІ АТРИБУТИ КОМПІЛЯТОРА: Атрибут [Obsolete] (Деніел Соліс, с. 701)
/// =========================================================================================
/// Демонструє використання атрибута [Obsolete] для маркування застарілих елементів коду.
/// Відповідає матеріалу книги Daniel Solis "Illustrated C#", сторінка 701 (базовий виклик).
/// 
/// ЗВ'ЯЗОК З ІНШИМИ ПРОЄКТАМИ:
/// - Цей проєкт (p701[SOLIS]) демонструє 1-й варіант конструктора [Obsolete("Повідомлення")].
/// - Проєкт 'attribute-exmple-02' демонструє розширену версію зі с. 701-702: [Obsolete("...", false/true)].
/// 
/// ТЕОРЕТИЧНІ АСПЕКТИ:
/// 1. Атрибут [Obsolete] інструктує компілятор C# генерувати попередження (CS0618) або
///    помилку компіляції (CS0619), якщо викликається позначений метод, клас чи властивість.
/// 2. Сигнатури конструктора:
///    - [Obsolete] -> стандартне попередження без уточнення.
///    - [Obsolete("Повідомлення")] -> попередження з текстом рекомендації нової альтернативи.
///    - [Obsolete("Повідомлення", error: true)] -> фатальна помилка компіляції (код не збігається).
/// 3. На рівні метаданих збірки інформація про застарілість зберігається в таблиці CustomAttribute (0x0C),
///    тому IDE (Visual Studio, Rider) підкреслюють виклик закресленим шрифтом.
/// </summary>
class Program
{
    // Маркуємо застарілий метод із рекомендацією використовувати альтернативу:
    [Obsolete("Use method SuperPrintOut")] // Apply attribute to method.
    static void PrintOut(string str)
    {
        Console.WriteLine(str);
    }

    static void Main(string[] args)
    {
        // При компіляції цього рядка компілятор згенерує попередження CS0618:
        // "'Program.PrintOut(string)' is obsolete: 'Use method SuperPrintOut'"
        PrintOut("Start of Main"); // Invoke obsolete method.
    }
}
