#define DoTrace
using System;
using System.Diagnostics;

namespace AttributesConditional
{
    /// <summary>
    /// =========================================================================================
    /// СИСТЕМНІ АТРИБУТИ КОМПІЛЯТОРА: Умовна компіляція [Conditional] (Деніел Соліс, с. 703)
    /// =========================================================================================
    /// Демонструє приклад зі сторінки 703 книги Daniel Solis "Illustrated C#".
    /// Робота атрибута [Conditional] із простору імен System.Diagnostics.
    /// 
    /// ТЕОРЕТИЧНІ АСПЕКТИ:
    /// 1. Атрибут [Conditional("SYMBOL")] змушує компілятор Roslyn повністю ВИДАЛЯТИ ВИКЛИКИ
    ///    методу з бінарного коду (IL), якщо символ умовної компіляції SYMBOL не визначено.
    /// 2. Сам метод завжди компілюється в збірку, але в місцях його виклику (call-sites)
    ///    інструкція call/callvirt просто пропускається компілятором.
    /// 3. Жорсткі обмеження для методів з [Conditional]:
    ///    - Метод зобов'язаний повертати void (оскільки не можна опустити виклик функції, що повертає значення).
    ///    - Метод не може бути реалізацією інтерфейсу.
    ///    - Метод не може мати out-параметрів.
    /// 4. Перевага над директивами препроцесора #if...#endif:
    ///    Код залишається чистішим, не засмічується директивами навколо кожного виклику логування.
    /// </summary>
    class Program
    {
        // Метод буде викликатися лише якщо визначено символ 'DoTrace' (через #define або build flags)
        [Conditional("DoTrace")]
        static void TraceMessage(string str)
        {
            Console.WriteLine(str);
        }

        static void Main()
        {
            // Якщо закоментувати рядок #define DoTrace на початку файлу,
            // виклики TraceMessage будуть повністю вилучені компілятором з фінального IL-коду!
            TraceMessage("Start of Main");
            Console.WriteLine("Doing work in Main.");
            TraceMessage("End of Main");
        }
    }
}
