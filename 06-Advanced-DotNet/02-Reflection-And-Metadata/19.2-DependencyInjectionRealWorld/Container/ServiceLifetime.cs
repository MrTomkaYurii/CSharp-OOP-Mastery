namespace DependencyInjection.Container;

/// <summary>
/// Життєвий цикл сервісу в IoC-контейнері.
/// Визначає стратегію створення та збереження екземплярів типів у пам'яті.
/// </summary>
public enum ServiceLifetime
{
    /// <summary>
    /// Новий екземпляр створюється під час кожного звернення до контейнера.
    /// Не кешується контейнером; знищується збирачем сміття (GC) після втрати посилань.
    /// </summary>
    Transient,

    /// <summary>
    /// Єдиний екземпляр створюється один раз під час першого звернення
    /// та зберігається в пам'яті контейнера на весь час життя додатка.
    /// </summary>
    Singleton
}
