using System;
using System.Collections.Generic;
using System.Linq;

namespace SetOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор Except (Різниця двох множин)
    // ==============================================================================================
    // Категорія: Set Operators (Оператори над множинами)
    // Призначення: Повертає елементи з першої послідовності, які ВІДСУТНІ в другій послідовності (A \ B).
    //
    // Принцип роботи:
    //   - Створює хеш-множину (HashSet) з елементів другої колекції B.
    //   - Проходить по першій колекції A: якщо елемент відсутній у множині B, він повертається
    //     та додається у внутрішній фільтр унікальності (щоб не повторюватися).
    //   - Зверніть увагу: порядок аргументів має вирішальне значення! A.Except(B) != B.Except(A).
    //
    // Тип виконання:
    //   - Відкладене виконання (Deferred Execution, Streaming).
    // ==============================================================================================

    public partial class LinqSamplesSetOperators
    {
        /// <summary>
        /// Приклад 52: Використання оператора Except для знаходження чисел, які є в першому масиві, але відсутні в другому.
        /// </summary>
        public void Linq52()
        {
            int[] numbersA = { 0, 2, 4, 5, 6, 8, 9 };
            int[] numbersB = { 1, 3, 5, 7, 8 };

            #region LINQ Method Syntax (Except)

            // Числа 5 і 8 є в numbersB, тому вони виключаються. Залишаються: 0, 2, 4, 6, 9.
            IEnumerable<int> aOnlyNumbers = numbersA.Except(numbersB);

            Console.WriteLine("Числа з першого масиву, яких немає в другому (A \\ B):");
            foreach (var n in aOnlyNumbers)
            {
                Console.WriteLine(n);
            }

            #endregion
        }
    }
}
