using System;
using System.Linq;

namespace SetOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор Union (Об'єднання множин без дублікатів)
    // ==============================================================================================
    // Категорія: Set Operators (Оператори над множинами)
    // Призначення: Математичне об'єднання двох послідовностей (A ∪ B), що містить усі унікальні
    //              елементи з обох джерел без повторень.
    //
    // Відмінність від Concat:
    //   - Concat() просто з'єднує послідовності A та B (A + B), зберігаючи всі дублікати.
    //   - Union() об'єднує послідовності та видаляє всі дублікати (еквівалент Concat().Distinct()).
    //
    // Тип виконання:
    //   - Відкладене виконання (Deferred Execution, Streaming).
    // ==============================================================================================

    public partial class LinqSamplesSetOperators
    {
        /// <summary>
        /// Приклад 48: Використання оператора Union для об'єднання двох числових масивів без дублікатів.
        /// </summary>
        public void Linq48()
        {
            int[] numbersA = { 0, 2, 4, 5, 6, 8, 9 };
            int[] numbersB = { 1, 3, 5, 7, 8 };

            #region LINQ Method Syntax (Union)

            // Числа 5 і 8 є в обох масивах, але в результаті з'являться лише один раз
            var uniqueNumbers = numbersA.Union(numbersB);

            Console.WriteLine("Унікальні числа з обох масивів (Union):");
            foreach (var n in uniqueNumbers)
            {
                Console.WriteLine(n);
            }

            #endregion
        }
    }
}
