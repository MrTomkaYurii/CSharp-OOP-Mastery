using System;
using System.Linq;

namespace PartitioningOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор TakeWhile (Умовна вибірка з початку)
    // ==============================================================================================
    // Категорія: Partitioning Operators (Оператори розбиття / секціонування)
    // Призначення: Повертає елементи з початку послідовності доти, доки заданий предикат повертає true.
    //
    // Принцип роботи та відмінність від Where:
    //   - Where перевіряє ВСІ елементи колекції і повертає всі, що відповідають умові.
    //   - TakeWhile перевіряє елементи ПО ПОРЯДКУ від початку. Як тільки зустрічається ПЕРШИЙ елемент,
    //     для якого предикат повертає false, виконання НЕГАЙНО припиняється (навіть якщо далі знову йдуть
    //     елементи, які задовольняють умову).
    //
    // Тип виконання:
    //   - Відкладене виконання (Deferred Execution, Streaming, Short-circuiting).
    // ==============================================================================================

    public partial class LinqSamplesPartitioningOperators
    {
        /// <summary>
        /// Приклад 24: Вибірка елементів із початку масиву, доки не зустрінеться число, не менше за 6.
        /// </summary>
        public void Linq24()
        {
            // Масив: { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 }
            // 5 < 6 (так), 4 < 6 (так), 1 < 6 (так), 3 < 6 (так), 9 < 6 (НІ! Зупинка).
            // Решта чисел (навіть 2 і 0) оброблятися не будуть!
            int[] numbers = { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 };

            #region LINQ Method Syntax (TakeWhile)

            var firstNumbersLessThan6 = numbers.TakeWhile(n => n < 6);

            Console.WriteLine("Перші числа, менші за 6 (до першого числа >= 6):");
            foreach (var num in firstNumbersLessThan6)
            {
                Console.WriteLine(num);
            }

            #endregion
        }
    }
}
