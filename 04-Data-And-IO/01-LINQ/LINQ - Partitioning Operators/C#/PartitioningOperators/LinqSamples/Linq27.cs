using System;
using System.Linq;

namespace PartitioningOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор SkipWhile з індексом (Indexed SkipWhile)
    // ==============================================================================================
    // Категорія: Partitioning Operators (Оператори розбиття / секціонування)
    // Призначення: Пропускає елементи з початку послідовності, доки елемент та його індекс задовольняють умову.
    //
    // Принцип роботи:
    //   - Перевантаження: SkipWhile<TSource>(this IEnumerable<TSource> source, Func<TSource, int, bool> predicate).
    //   - Пропускає елементи, для яких умова (n, index) істинна.
    //   - Як тільки для певного елемента умова повертає false, цей елемент і всі наступні за ним повертаються.
    //
    // Тип виконання:
    //   - Відкладене виконання (Deferred Execution, Streaming).
    // ==============================================================================================

    public partial class LinqSamplesPartitioningOperators
    {
        /// <summary>
        /// Приклад 27: Пропуск елементів із початку, доки значення не менше за індекс (n >= index).
        /// Повертає перший елемент, менший за свій індекс, і всі наступні елементи до кінця масиву.
        /// </summary>
        public void Linq27()
        {
            // Масив: { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 }
            // Індекс 0: 5 >= 0 (так, пропуск)
            // Індекс 1: 4 >= 1 (так, пропуск)
            // Індекс 2: 1 >= 2 (НІ! Умова false -> пропуск завершено).
            // Повертаються елементи: 1, 3, 9, 8, 6, 7, 2, 0
            int[] numbers = { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 };

            #region LINQ Method Syntax (Indexed SkipWhile)

            var laterNumbers = numbers.SkipWhile((n, index) => n >= index);

            Console.WriteLine("Усі елементи, починаючи з першого, меншого за свій індекс:");
            foreach (var n in laterNumbers)
            {
                Console.WriteLine(n);
            }

            #endregion
        }
    }
}
