using System;
using System.Linq;

namespace AggregateOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор Min (Пошук мінімального елемента)
    // ==============================================================================================
    // Категорія: Aggregate Operators (Агрегатні оператори)
    // Призначення: Повертає мінімальне значення з числової або порівнюваної (IComparable) послідовності.
    //
    // Принцип роботи:
    //   - Проходить по всій колекції за один цикл O(N), відстежуючи мінімальний знайдений елемент.
    //   - Якщо послідовність порожня, для не-nullable типів викидає System.InvalidOperationException.
    //   - Працює з будь-якими типами, що реалізують IComparable<T>.
    //
    // Тип виконання:
    //   - Негайне виконання (Immediate Execution).
    // ==============================================================================================

    public partial class LinqSamplesAggregateOperators
    {
        /// <summary>
        /// Приклад 81: Знаходження мінімального числа в масиві за допомогою Min.
        /// </summary>
        public void Linq81()
        {
            int[] numbers = { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 };

            #region Make Sure to try yourself before looking at the code

            // Знаходимо мінімальний елемент масиву
            int minNum = numbers.Min();

            #endregion

            Console.WriteLine("The minimum number is {0}.", minNum);
        }
    }
}
