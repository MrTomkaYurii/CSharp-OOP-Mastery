using System;
using System.Linq;

namespace AggregateOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор Count з предикатом
    // ==============================================================================================
    // Категорія: Aggregate Operators (Агрегатні оператори)
    // Призначення: Підраховує кількість елементів у послідовності, які задовольняють задану умову (предикат).
    //
    // Принцип роботи:
    //   - Еквівалентний виклику .Where(predicate).Count(), але оптимізований в один прохід без створення проміжного ітератора.
    //   - Повертає ціле число типу int.
    //   - Для дуже великих колекцій (понад 2 млрд елементів) існує метод LongCount().
    //
    // Тип виконання:
    //   - Негайне виконання (Immediate Execution).
    // ==============================================================================================

    public partial class LinqSamplesAggregateOperators
    {
        /// <summary>
        /// Приклад 74: Підрахунок кількості непарних чисел у масиві за допомогою Count(predicate).
        /// </summary>
        public void Linq74()
        {
            int[] numbers = { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 };

            #region Make Sure to try yourself before looking at the code

            // Підраховуємо лише числа, залишок від ділення яких на 2 дорівнює 1
            int oddNumbers = numbers.Count(n => n % 2 == 1);

            #endregion

            Console.WriteLine("There are {0} odd numbers in the list.", oddNumbers);
        }
    }
}
