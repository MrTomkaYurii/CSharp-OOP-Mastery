using System;
using System.Linq;

namespace AggregateOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор Sum (Сума числових елементів)
    // ==============================================================================================
    // Категорія: Aggregate Operators (Агрегатні оператори)
    // Призначення: Обчислює суму послідовності числових значень (int, double, decimal, float, long тощо).
    //
    // Принцип роботи:
    //   - Проходить по всій колекції та накопичує арифметичну суму.
    //   - Якщо послідовність порожня, повертає 0 (для не-nullable числових типів).
    //   - Для типів з фіксованою розрядністю (int, long) при виході за межі діапазону в перевіреному (checked) контексті
    //     може викликати OverflowException.
    //
    // Тип виконання:
    //   - Негайне виконання (Immediate Execution).
    // ==============================================================================================

    public partial class LinqSamplesAggregateOperators
    {
        /// <summary>
        /// Приклад 78: Обчислення загальної суми чисел у масиві за допомогою Sum.
        /// </summary>
        public void Linq78()
        {
            int[] numbers = { 5, 4, 1, 3, 9, 8, 6, 7, 2, 0 };

            #region Make Sure to try yourself before looking at the code

            // Обчислюємо арифметичну суму всіх елементів масиву
            double numSum = numbers.Sum();

            #endregion

            Console.WriteLine("The sum of the numbers is {0}.", numSum);
        }
    }
}
