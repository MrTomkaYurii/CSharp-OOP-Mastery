using System;
using System.Linq;

namespace AggregateOperators
{
    // ==============================================================================================
    // ТЕОРЕТИЧНА ДОВІДКА: Оператор Max з селектором
    // ==============================================================================================
    // Категорія: Aggregate Operators (Агрегатні оператори)
    // Призначення: Знаходить максимальне значення проектованої числової або порівнюваної властивості.
    //
    // Принцип роботи:
    //   - Застосовує вказану функцію (селектор) до кожного елемента й повертає максимальне отримане значення.
    //   - Повертає значення результату функції (у даному випадку int — довжину найдовшого слова).
    //   - У .NET 6+ для повернення самого об'єкта (слова) використовується MaxBy(w => w.Length).
    //
    // Тип виконання:
    //   - Негайне виконання (Immediate Execution).
    // ==============================================================================================

    public partial class LinqSamplesAggregateOperators
    {
        /// <summary>
        /// Приклад 86: Знаходження довжини найдовшого слова в масиві за допомогою Max(w => w.Length).
        /// </summary>
        public void Linq86()
        {
            string[] words = { "cherry", "apple", "blueberry" };

            #region Make Sure to try yourself before looking at the code

            // Отримуємо максимальну довжину серед слів (blueberry = 9 символів)
            int longestLength = words.Max(w => w.Length);

            #endregion

            Console.WriteLine("The longest word is {0} characters long.", longestLength);
        }
    }
}
