// ============================================================================
// Тема: Індексатор (indexer) — звернення до об'єкта як до масиву: obj[index]
// ----------------------------------------------------------------------------
// Індексатор — це особлива властивість із параметром у квадратних дужках.
// Оголошується як "public тип this[тип параметра]" і має акcесори get/set.
//   * при читанні  a[0]      викликається get, параметр index = 0;
//   * при записі    a[0] = 15 викликається set, index = 0, а неявний параметр
//     value містить присвоюване значення (тут 15).
// Індексатор дозволяє інкапсулювати внутрішнє сховище (тут — два окремі поля)
// за зручним "індексним" інтерфейсом.
// ============================================================================

class Class1
{
    int Temp0;                    // приватне поле — "комірка 0"
    int Temp1;                    // приватне поле — "комірка 1"

    public int this[int index]    // індексатор: ключ типу int, значення типу int
    {
        get
        {
            // index == 0 => повертаємо Temp0, будь-який інший index => Temp1
            return (0 == index)
                        ? Temp0
                        : Temp1;
        }
        set
        {
            // value — неявний параметр set-акcесора: те, що стоїть праворуч від "="
            if (0 == index)
                Temp0 = value;       // a[0] = ... записує у Temp0
            else
                Temp1 = value;       // a[будь-що інше] = ... записує у Temp1
        }
    }
}

class Example
{
    static void Main()
    {
        Class1 a = new Class1();

        // Temp0 і Temp1 ще не присвоювали => int за замовчуванням = 0
        Console.WriteLine("Values -- T0: {0}, T1: {1}", a[0], a[1]);   // T0: 0, T1: 0
        a[0] = 15;   // set(index:0, value:15) => Temp0 = 15
        a[1] = 20;   // set(index:1, value:20) => Temp1 = 20
        Console.WriteLine($"Values -- T0: {a[0]}, T1: {a[1]}");        // T0: 15, T1: 20
    }
}

