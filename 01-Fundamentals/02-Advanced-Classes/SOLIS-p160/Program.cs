// ============================================================================
// Тема: Ключове слово this — доступ до члена екземпляра, коли ім'я приховане
// ----------------------------------------------------------------------------
// this — це посилання на ПОТОЧНИЙ об'єкт, для якого викликано метод.
// Найчастіше this потрібне, коли локальне ім'я (параметр або локальна змінна)
// збігається з іменем поля класу і "перекриває" його. Тоді:
//   * Var1        — це параметр методу;
//   * this.Var1   — це поле того самого об'єкта.
// В інших випадках this можна не писати (компілятор і так звертається до поля).
// ============================================================================

class MyClass
{
    int Var1 = 10;   // поле екземпляра

    public int ReturnMaxSum(int Var1)   // параметр НАВМИСНО названий так само, як поле
    {
        // Тернарний оператор: якщо параметр більший за поле — повертаємо параметр,
        // інакше — значення поля.
        return Var1 > this.Var1
              ? Var1            // параметр методу
              : this.Var1;      // поле класу (this обов'язкове, бо ім'я перекрите)
    }
}

class Program
{
    static void Main()
    {
        MyClass mc = new MyClass();   // this.Var1 == 10

        Console.WriteLine($"Max: {mc.ReturnMaxSum(30)}");   // 30 > 10 => Max: 30
        Console.WriteLine($"Max: {mc.ReturnMaxSum(5)}");    //  5 > 10 хибно => Max: 10
    }
}

// ----------------------------------------------------------------------------
// Що можна додати:
//  * Той самий приклад БЕЗ перейменування параметра (parVar1) — показати, що
//    тоді this не потрібне взагалі.
//  * this у конструкторі для присвоєння полів (див. Ex-This-In-Constructor).
//  * Повернення this з методу для ланцюжка викликів (method chaining).
//  * Передачу this як аргумента в інший метод.
