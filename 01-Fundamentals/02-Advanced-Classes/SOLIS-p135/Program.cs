// ============================================================================
// Тема: Статичні поля (static fields) — одна спільна комірка на весь клас
// ----------------------------------------------------------------------------
// Статичне поле НЕ належить окремому об'єкту. Воно існує в єдиному екземплярі
// незалежно від того, скільки об'єктів класу створено (навіть якщо жодного).
// Усі екземпляри "бачать" і змінюють одне й те саме значення.
// Цей приклад навмисно контрастує з SOLIS-p132 (поле екземпляра).
// ============================================================================

class D
{
    int Mem1;          // Поле ЕКЗЕМПЛЯРА: у кожного об'єкта D власна копія Mem1
    static int Mem2;   // СТАТИЧНЕ поле: одне на весь клас, спільне для d1 і d2

    public void SetVars(int v1, int v2)   // Записати значення в обидва поля
    {
        Mem1 = v1;   // змінює поле ЛИШЕ поточного об'єкта (this.Mem1)
        Mem2 = v2;   // змінює СПІЛЬНЕ значення — його "побачать" усі об'єкти
    }

    public void Display(string str)
    {
        // Mem1 у різних об'єктів різне, а Mem2 завжди однакове для всіх
        Console.WriteLine("{0}: Mem1= {1}, Mem2= {2}", str, Mem1, Mem2);
    }
}

class Program
{
    static void Main()
    {
        D d1 = new D(), d2 = new D();   // Створюємо два незалежні об'єкти

        d1.SetVars(2, 4);              // d1.Mem1 = 2;  спільне Mem2 = 4
        d1.Display("d1");              // d1: Mem1= 2, Mem2= 4

        d2.SetVars(15, 17);           // d2.Mem1 = 15; спільне Mem2 стало 17
        d2.Display("d2");             // d2: Mem1= 15, Mem2= 17

        // Виводимо d1 ще раз. Зверніть увагу: d1.Mem1 не змінився (=2),
        // але статичне Mem2 тепер дорівнює 17 — його перезаписав виклик d2.SetVars!
        d1.Display("d1");            // d1: Mem1= 2, Mem2= 17
    }
}

