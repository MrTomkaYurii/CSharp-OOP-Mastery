// ============================================================================
// Тема: Частковий клас (partial class) та частковий метод (partial method)
// ----------------------------------------------------------------------------
// partial-клас дозволяє РОЗБИТИ оголошення одного класу на кілька частин
// (тут — на два блоки, зазвичай у різних файлах). Під час компіляції всі
// частини зливаються в один тип.
//
// partial-метод складається з двох частин:
//   * ОГОЛОШЕННЯ (сигнатура без тіла) — "обіцянка", що метод може бути;
//   * РЕАЛІЗАЦІЯ (та сама сигнатура з тілом) — необов'язкова.
// Якщо реалізації немає, компілятор ПОВНІСТЮ ВИДАЛЯЄ і оголошення, і всі
// виклики цього методу (тому класичний partial-метод має бути void, без
// out-параметрів і не може бути public). Це механізм "розширення" для
// згенерованого коду (наприклад, дизайнерів форм чи ORM).
// ============================================================================

partial class MyClass
{
    partial void PrintSum(int x, int y);   // ОГОЛОШЕННЯ часткового методу (без тіла)

    public void Add(int x, int y)
    {
        PrintSum(x, y);   // якщо реалізації немає — цей виклик просто зникне при компіляції
    }
}

partial class MyClass
{
    partial void PrintSum(int x, int y)     // РЕАЛІЗАЦІЯ часткового методу (з тілом)
    {
        Console.WriteLine("Sum is {0}", x + y);
    }
}

class Program
{
    static void Main()
    {
        var mc = new MyClass();
        mc.Add(5, 6);   // Add викликає реалізований PrintSum => "Sum is 11"
    }
}

