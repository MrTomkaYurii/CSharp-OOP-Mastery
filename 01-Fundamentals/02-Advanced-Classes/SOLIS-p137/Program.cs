// ============================================================================
// Тема: Статичні члени та доступ до них через ім'я класу (dot-syntax)
// ----------------------------------------------------------------------------
// До статичного поля й статичного методу звертаються НЕ через об'єкт, а через
// ім'я класу: ІмʼяКласу.Член. Об'єкт створювати не потрібно — статичні члени
// існують самі по собі, як тільки клас завантажено середовищем виконання.
// Статичний метод не має доступу до this і до полів екземпляра — лише до
// інших статичних членів.
// ============================================================================

class X
{
    static public int A;                       // Статичне поле: одне на весь клас X

    static public void PrintValA()             // Статичний метод: працює без об'єкта
    {
        // Усередині статичного методу доступні тільки статичні члени класу
        Console.WriteLine("Value of A: {0}", A);   // A — це те саме, що X.A
    }
}

class Program
{
    static void Main()
    {
        X.A = 10;          // Крапкова нотація: звертаємось до статичного поля через клас
        X.PrintValA();     // Так само викликаємо статичний метод — Value of A: 10
    }
}

