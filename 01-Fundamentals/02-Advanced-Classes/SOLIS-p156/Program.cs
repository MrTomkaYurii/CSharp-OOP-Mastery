// ============================================================================
// Тема: Статичний конструктор (static constructor)
// ----------------------------------------------------------------------------
// Статичний конструктор ініціалізує СТАТИЧНІ поля класу. Його особливості:
//   * не має модифікатора доступу і не має параметрів;
//   * його НЕ можна викликати вручну — середовище виконання саме викликає
//     його РІВНО ОДИН РАЗ, автоматично, перед першим використанням класу
//     (перед створенням першого об'єкта або першим зверненням до статичного
//     члена);
//   * гарантує потокобезпечну одноразову ініціалізацію.
// Тут він створює єдиний генератор випадкових чисел, спільний для всіх об'єктів.
// ============================================================================

class RandomNumberClass
{
    private static Random RandomKey;   // приватне статичне поле: один генератор на клас

    static RandomNumberClass()         // статичний конструктор (без модифікаторів і параметрів)
    {
        RandomKey = new Random();       // виконається один раз перед першим використанням класу
    }

    public int GetRandomNumber()
    {
        return RandomKey.Next();         // усі екземпляри користуються тим самим RandomKey
    }
}

class Program
{
    static void Main()
    {
        RandomNumberClass a = new RandomNumberClass();
        RandomNumberClass b = new RandomNumberClass();
        // Статичний конструктор відпрацював лише раз (при створенні a).
        // Об'єкт b використовує вже наявний RandomKey.

        Console.WriteLine("Next Random #: {0}", a.GetRandomNumber());
        Console.WriteLine($"Next Random #: {b.GetRandomNumber()}");
    }
}

