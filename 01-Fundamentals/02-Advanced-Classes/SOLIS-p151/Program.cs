// ============================================================================
// Тема: Статична властивість + директива "using static"
// ----------------------------------------------------------------------------
// Приклад показує дві речі:
//  1) Статична автовластивість MyValue належить класу Trivial (одна на весь
//     клас), тому звертаються до неї як Trivial.MyValue.
//  2) Директива "using static ConsoleTestApp.Trivial;" імпортує статичні члени
//     класу Trivial у поточну область видимості, тож усередині Main можна
//     писати просто MyValue замість Trivial.MyValue.
//  Також видно, що метод екземпляра (PrintValue) може вільно читати статичний
//  член свого класу.
// ============================================================================

using static ConsoleTestApp.Trivial;   // імпорт статичних членів класу Trivial

namespace ConsoleTestApp
{
    class Trivial
    {
        // Статична автовластивість: спільна для всіх, живе без створення об'єкта
        public static int MyValue { get; set; }

        public void PrintValue()
        {
            // Метод екземпляра має доступ до статичного члена свого класу
            Console.WriteLine("Value from inside: {0}", MyValue);
        }
    }

    class Program
    {
        static void Main()
        {
            // Початкове значення int-властивості = 0 (нічого ще не присвоювали)
            Console.WriteLine("Init Value: {0}", Trivial.MyValue);   // Init Value: 0

            Trivial.MyValue = 10;                                    // запис через ім'я класу
            Console.WriteLine("New Value : {0}", Trivial.MyValue);   // New Value : 10

            // Завдяки "using static" ім'я класу можна не писати — це та сама властивість
            MyValue = 20;                                            // рівнозначно Trivial.MyValue = 20
            Console.WriteLine($"New Value : {MyValue}");             // New Value : 20

            Trivial tr = new Trivial();
            tr.PrintValue();                                         // Value from inside: 20
        }
    }
}

