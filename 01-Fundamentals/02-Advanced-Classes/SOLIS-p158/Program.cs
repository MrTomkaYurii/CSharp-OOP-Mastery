// ============================================================================
// Тема: Ініціалізатор об'єкта (object initializer)
// ----------------------------------------------------------------------------
// Синтаксис "new Type { Поле = значення, Властивість = значення }" дозволяє
// одразу після виклику конструктора присвоїти доступні поля/властивості
// об'єкта без окремих рядків присвоєння. Порядок дій:
//   1) виконується конструктор (тут — неявний конструктор без параметрів);
//   2) потім по черзі присвоюються члени, перелічені у фігурних дужках.
// Зручно, коли клас не має конструктора з потрібним набором параметрів.
// ============================================================================

public class Point
{
    public int X = 1;   // значення за замовчуванням, якщо його не перевизначити
    public int Y = 2;
}

class Program
{
    static void Main()
    {
        // Без ініціалізатора: спрацьовує лише конструктор => X=1, Y=2
        Point pt1 = new Point();

        // З ініціалізатором: конструктор дає X=1,Y=2, далі присвоєння => X=5, Y=6
        Point pt2 = new Point { X = 5, Y = 6 };

        Console.WriteLine("pt1: {0}, {1}", pt1.X, pt1.Y);   // pt1: 1, 2
        Console.WriteLine($"pt2: {pt2.X}, {pt2.Y}");        // pt2: 5, 6
    }
}

// ----------------------------------------------------------------------------
// Що можна додати:
