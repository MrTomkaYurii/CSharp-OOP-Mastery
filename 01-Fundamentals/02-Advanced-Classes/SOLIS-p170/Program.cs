// ============================================================================
// Тема: Властивість із різними рівнями доступу акcесорів (asymmetric accessors)
// ----------------------------------------------------------------------------
// Акcесори get і set можуть мати РІЗНІ модифікатори доступу. Типовий випадок:
//   public string Name { get; private set; }
//   * get — public: значення можна читати звідусіль;
//   * set — private: змінювати можна ЛИШЕ всередині самого класу
//     (зазвичай у конструкторі).
// Ззовні об'єкт виглядає незмінним ("тільки для читання"), але клас зберігає
// можливість керувати своїм станом. Обмежувальний модифікатор ставиться лише
// на ОДИН акcесор і має бути суворішим за модифікатор самої властивості.
// ============================================================================

class Person
{
    // Читати p.Name можна ззовні; присвоїти p.Name = "..." ззовні — не можна
    public string Name { get; private set; }

    public Person(string name)
    {
        Name = name;   // всередині класу private set доступний => це працює
    }
}

class Program
{
    static public void Main()
    {
        Person p = new Person("Capt. Ernest Evans");
        Console.WriteLine($"Person's name is {p.Name}");   // читання через public get

        // p.Name = "Інше ім'я";  // <- помилка компіляції: set недоступний ззовні
    }
}

