// ============================================================================
// Тема: Перевантаження конструкторів (constructor overloading)
// ----------------------------------------------------------------------------
// Клас може мати кілька конструкторів, якщо вони відрізняються СИГНАТУРОЮ
// (кількістю або типами параметрів). Під час new компілятор обирає той
// конструктор, що відповідає переданим аргументам. Це дає різні способи
// створити об'єкт залежно від наявних вхідних даних.
// Недолік цього прикладу: кожен конструктор ОКРЕМО ініціалізує поля, тобто
// логіка частково дублюється. Як цього уникнути через ": this(...)" —
// показано в Ex-This-In-Constructor та Ex-This-In-Constructor-02.
// ============================================================================

class Class1
{
    int Id;        // поле екземпляра (за замовчуванням 0)
    string Name;   // поле екземпляра (за замовчуванням null)

    // Конструктор 0: без параметрів. Задає значення "за замовчуванням".
    public Class1() { Id = 28; Name = "Nemo"; }
    // Конструктор 1: приймає число => це Id, ім'я лишається типовим.
    public Class1(int val) { Id = val; Name = "Nemo"; }
    // Конструктор 2: приймає рядок => це Name; Id НЕ присвоюється, тож лишиться 0.
    public Class1(String name) { Name = name; }

    public void SoundOff()
    {
        Console.WriteLine($"Name {Name}, Id {Id}");
    }
}

class Program
{
    static void Main()
    {
        Class1 a = new Class1(),          // виклик конструктора 0 => Id=28, Name="Nemo"
               b = new Class1(7),         // виклик конструктора 1 => Id=7,  Name="Nemo"
               c = new Class1("Bill");    // виклик конструктора 2 => Id=0,  Name="Bill"

        a.SoundOff();   // Name Nemo, Id 28
        b.SoundOff();   // Name Nemo, Id 7
        c.SoundOff();   // Name Bill, Id 0   <- Id не задавали, тому 0
    }
}

