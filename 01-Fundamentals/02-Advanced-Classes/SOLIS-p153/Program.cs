//  * Конструктор з двома параметрами public Class1(int val, string name).
//  * Показати неоднозначність виклику new Class1(null) — компілятор не знає,
//    який конструктор обрати (потрібне явне приведення (string)null).
//  * Значення параметрів за замовчуванням: public Class1(int id = 28, string name = "Nemo").
