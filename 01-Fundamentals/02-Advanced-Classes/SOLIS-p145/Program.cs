// ============================================================================
// Тема: Властивості (properties) та поле для зберігання даних (backing field)
// ----------------------------------------------------------------------------
// Властивість — це пара акcесорів get/set, які ЗОВНІ виглядають як поле, а
// всередині є методами. Властивість сама по собі НЕ зберігає дані: вона
// читає/записує окреме приватне поле, яке називають backing field
// ("поле-сховище"). Такий підхід дає інкапсуляцію: клас контролює доступ і
// може додати перевірки, обчислення, логування, не змінюючи зовнішній код.
// ============================================================================

class C1
{
    private int theRealValue = 10;   // Backing field: САМЕ ТУТ виділяється пам'ять
                                     // під значення. Поле private — ззовні недоступне.

    public int MyValue               // Властивість: власної пам'яті не має,
    {                                // це "обгортка" навколо theRealValue
        set { theRealValue = value; }  // set-акcесор: неявний параметр value містить
                                       // те, що присвоюють (c.MyValue = 20 => value = 20)
        get { return theRealValue; }   // get-акcесор: повертає поточне значення поля
    }
}

class Program
{
    static void Main()
    {
        C1 c = new C1();
        Console.WriteLine("MyValue: {0}", c.MyValue);   // читання => виклик get => 10

        c.MyValue = 20;                                 // запис => виклик set (value=20)
        Console.WriteLine("MyValue: {0}", c.MyValue);   // знову get => 20
    }
}

// ----------------------------------------------------------------------------
// Що можна додати:
//  * Перевірку в set: if (value < 0) throw new ArgumentOutOfRangeException(...).
//  * Властивість тільки для читання (лише get) — див. SOLIS-p149.
