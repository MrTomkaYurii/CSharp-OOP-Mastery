// ============================================================================
// Тема: Автоматично реалізовані властивості (auto-implemented properties)
// ----------------------------------------------------------------------------
// Якщо властивості потрібне просте зберігання значення без додаткової логіки,
// можна не писати backing field вручну. Достатньо оголосити get; та set;
// без тіла — компілятор САМ згенерує приховане приватне поле і код акcесорів.
// Тобто, на відміну від SOLIS-p145, тут пам'ять під дані все одно виділяється,
// просто поле недоступне за іменем у коді.
// (Порядок get/set значення не має: "set; get;" рівнозначно "get; set;".)
// ============================================================================

class C1
{
    public int MyValue   // Автовластивість: компілятор створює приховане поле int
    {
        set; get;        // порожні акcесори => згенерований код: field = value / return field
    }
}

class Program
{
    static void Main()
    {
        C1 c = new C1();
        // Приховане поле ще не присвоювали => значення за замовчуванням для int = 0
        Console.WriteLine("MyValue: {0}", c.MyValue);   // MyValue: 0

        c.MyValue = 20;                                 // set записує 20 у приховане поле
        Console.WriteLine("MyValue: {0}", c.MyValue);   // MyValue: 20
    }
}

// ----------------------------------------------------------------------------
// Що можна додати:
//  * Ініціалізатор автовластивості: public int MyValue { get; set; } = 5;
//  * Автовластивість тільки для читання: public int Id { get; } — присвоюється
//    лише в конструкторі (див. Ex-Indexers-01, SOLIS-p170).
//  * init-акcесор (C# 9): public int MyValue { get; init; } — присвоєння лише
//    під час ініціалізації об'єкта.
//  * Пояснити, коли auto-property НЕ підходить (потрібна валідація, обчислення).
// ----------------------------------------------------------------------------
