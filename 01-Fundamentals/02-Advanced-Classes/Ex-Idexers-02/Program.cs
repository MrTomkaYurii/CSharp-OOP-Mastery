// ============================================================================
// Тема: Перевантаження індексаторів — кілька індексаторів з різними типами ключа
// ----------------------------------------------------------------------------
// Один клас може мати кілька індексаторів, якщо вони відрізняються типом
// (або кількістю) параметрів. Тут:
//   * this[int index]   — доступ до імені за числовою позицією (get + set);
//   * this[string name]  — зворотний пошук: за іменем повертає його індекс
//     (лише get).
// Обидва індексатори працюють поверх одного приватного масиву namelist.
// Також показано безпечну поведінку: некоректний індекс не кидає виняток,
// а повертає "" (для get) або ігнорує запис (для set).
// ============================================================================

class IndexedNames
{
    static public int size = 10;                       // місткість сховища (статичне поле)
    private string[] namelist = new string[size];      // приватний масив імен

    public IndexedNames()
    {
        // Заповнюємо масив заглушкою "N. A." (not available), щоб не було null
        for (int i = 0; i < size; i++)
        {
            namelist[i] = "N. A.";
        }
    }

    // Індексатор №1: ключ int -> рядок (ім'я на позиції index)
    public string this[int index]
    {
        get
        {
            string tmp;

            // Перевірка меж: коректний діапазон 0..size-1
            if (index >= 0 && index <= size - 1)
            {
                tmp = namelist[index];
            }
            else
            {
                tmp = "";          // некоректний індекс => повертаємо порожній рядок (без винятку)
            }

            return (tmp);
        }
        set
        {
            // Запис лише в межах масиву; поза межами — тихо ігнорується
            if (index >= 0 && index <= size - 1)
            {
                namelist[index] = value;   // value — присвоюване ім'я
            }
        }
    }

    // Індексатор №2: ключ string -> int (позиція, на якій стоїть це ім'я)
    public int this[string name]
    {
        get
        {
            int index = 0;

            // Лінійний пошук імені в масиві
            while (index < size)
            {
                if (namelist[index] == name)
                {
                    return index;          // знайшли => повертаємо позицію
                }
                index++;
            }
            return index;                  // не знайшли => повертаємо size (== кількість елементів)
        }
    }
}

public static class Program
{
    static void Main(string[] args)
    {
        IndexedNames names = new IndexedNames();
        names[0] = "Zara";       // виклик set індексатора №1
        names[1] = "Riz";
        names[2] = "Nuha";
        names[3] = "Asif";
        names[4] = "Davinder";
        names[5] = "Sunil";
        names[6] = "Rubic";
        // позиції 7..9 лишаються "N. A."

        // Використовуємо перший індексатор (ключ int) — друкуємо всі імена
        for (int i = 0; i < IndexedNames.size; i++)
        {
            Console.WriteLine(names[i]);
        }

        // Використовуємо другий індексатор (ключ string) — друкуємо позицію "Nuha" => 2
        Console.WriteLine(names["Nuha"]);
        Console.ReadKey();
    }
}

