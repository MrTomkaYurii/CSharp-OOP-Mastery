// ============================================================================
// Тема: Поля екземпляра (instance fields) — у кожного об'єкта своя копія даних
// ----------------------------------------------------------------------------
// Кожен раз, коли ми створюємо об'єкт через new, у пам'яті (у купі, heap)
// виділяється окрема ділянка під усі НЕстатичні поля цього об'єкта.
// Тому зміна поля одного об'єкта НЕ впливає на таке саме поле іншого об'єкта.
// Порівняйте цей приклад із SOLIS-p135, де показано протилежну поведінку
// статичного поля (спільного для всіх екземплярів).
// ============================================================================

class D
{
    // Public-поле екземпляра. "Поле екземпляра" означає, що для КОЖНОГО
    // об'єкта класу D створюється власна незалежна комірка Mem1.
    // (У навчальних цілях поле зроблено public; на практиці поля тримають
    // private і відкривають доступ через властивості — див. SOLIS-p145.)
    public int Mem1;
}

class Program
{
    static void Main()
    {
        D d1 = new D();   // Створюємо перший об'єкт: у пам'яті з'являється d1.Mem1
        D d2 = new D();   // Створюємо другий об'єкт: окрема комірка d2.Mem1

        d1.Mem1 = 10;     // Записуємо значення лише в поле об'єкта d1
        d2.Mem1 = 28;     // Записуємо значення лише в поле об'єкта d2 — d1 не змінюється

        // Виведе: d1 = 10, d2 = 28 — значення незалежні одне від одного
        Console.WriteLine($"d1 = {d1.Mem1}, d2 = {d2.Mem1}");
    }
}

