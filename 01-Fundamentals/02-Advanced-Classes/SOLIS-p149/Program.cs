// ============================================================================
// Тема: Властивість тільки для читання (read-only property) з обчисленням
// ----------------------------------------------------------------------------
// Якщо у властивості є лише get-акcесор (без set), ззовні її можна тільки
// читати, але не присвоювати. Значення не обов'язково зберігати в полі —
// його можна ОБЧИСЛЮВАТИ щоразу при зверненні. Тут Hypotenuse (гіпотенуза)
// рахується з катетів A і B за теоремою Піфагора в момент читання.
// Це приклад "похідної" властивості: вона не займає пам'яті під дані й
// завжди узгоджена з полями, від яких залежить.
// ============================================================================

class RightTriangle   // прямокутний трикутник
{
    public double A = 3;   // довжина першого катета
    public double B = 4;   // довжина другого катета

    public double Hypotenuse                              // Властивість лише для читання
    {
        // Немає set — присвоїти c.Hypotenuse = 10 не можна (помилка компіляції).
        // get обчислює гіпотенузу: sqrt(A^2 + B^2). Для A=3, B=4 => 5.
        get { return Math.Sqrt((A * A) + (B * B)); }      // обчислюємо значення для повернення
    }
}

class Program
{
    static void Main()
    {
        RightTriangle c = new RightTriangle();
        Console.WriteLine($"Hypotenuse: {c.Hypotenuse}");   // Hypotenuse: 5
    }
}

