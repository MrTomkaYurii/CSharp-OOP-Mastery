// ============================================================================
// Тема: Константи-члени класу (const) та доступ до них
// ----------------------------------------------------------------------------
// const-поле — це іменована незмінна величина, значення якої відоме вже під
// час компіляції. Ключові властивості const:
//   * значення задається один раз при оголошенні і НІКОЛИ не змінюється;
//   * const неявно є static — звертаються до нього через ім'я класу (X.PI),
//     окремий об'єкт не потрібен і навіть не можна писати "static const";
//   * компілятор підставляє саме значення в місце використання (inline),
//     тому зміна const у бібліотеці потребує перекомпіляції залежного коду.
// Якщо значення має обчислюватися під час виконання — потрібне static readonly.
// ============================================================================

class X
{
    // Константа: тип double, значення 3.1416, доступна як X.PI
    public const double PI = 3.1416;
}

class Program
{
    static void Main()
    {
        // Використовуємо константу через ім'я класу. Спроба X.PI = 3.15
        // не скомпілюється — константу присвоїти не можна.
        Console.WriteLine($"pi = {X.PI}");   // pi = 3.1416
    }
}

// ----------------------------------------------------------------------------
// Що можна додати:
//  * Порівняння const і static readonly: readonly-поле можна задати в
//    конструкторі й воно не інлайниться (безпечніше для публічних API).
//  * Локальну константу всередині методу: const int Max = 100;
//  * Константу, що посилається на іншу константу: public const double TwoPi = 2 * PI;
//  * Демонстрацію, що const допустимий лише для примітивів, string і null-посилань.
