// ============================================================================
// Тема: Конструктор за замовчуванням vs конструктор з параметрами
// ----------------------------------------------------------------------------
// "Конструктор за замовчуванням" (default / parameterless) — це конструктор
// без параметрів. Важливо:
//   * якщо клас НЕ оголошує жодного конструктора, компілятор автоматично
//     додає порожній public-конструктор без параметрів;
//   * щойно ми оголошуємо БУДЬ-ЯКИЙ власний конструктор (напр. з параметрами),
//     автоматичний більше НЕ додається — за потреби його треба написати
//     явно (як тут MyClass()).
// Цей приклад показує обидва варіанти в одному класі й різницю в стані об'єкта.
// ============================================================================

using System;

public class MyClass
{
    public int Number { get; set; }          // автовластивість (int, за замовчуванням 0)
    public string StringValue { get; set; }  // автовластивість (string, за замовчуванням null)

    // Конструктор за замовчуванням (без параметрів) — задає "порожній" стан
    public MyClass()
    {
        // Явно виставляємо осмислені значення за замовчуванням
        Number = 0;
        StringValue = "Empty string";
    }

    // Перевантажений конструктор з параметрами — створює об'єкт із заданими даними
    public MyClass(int number, string stringValue)
    {
        Number = number;
        StringValue = stringValue;
    }

    public void DisplayInfo()
    {
        Console.WriteLine($"Number: {Number}, String: {StringValue}");
    }
}

class Program
{
    static void Main()
    {
        // Створюємо об'єкт через конструктор за замовчуванням
        MyClass object1 = new MyClass();
        object1.DisplayInfo();   // Number: 0, String: Empty string

        // Створюємо об'єкт через конструктор з параметрами
        MyClass object2 = new MyClass(42, "Hello, world!");
        object2.DisplayInfo();   // Number: 42, String: Hello, world!
    }
}

