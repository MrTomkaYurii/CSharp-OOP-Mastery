// Кілька необов'язкових параметрів. Пропускати аргументи (при позиційному виклику)
// можна лише "з хвоста": не можна задати a і c, пропустивши b —
// для цього знадобилися б іменовані аргументи (див. p123).

class MyClass
{
    public int Calc(int a = 2, int b = 3, int c = 4)
    {
        return (a + b) * c;
    }

    static void Main()
    {
        MyClass mc = new MyClass();
        int r0 = mc.Calc(5, 6, 7);  // a=5, b=6, c=7  => (5+6)*7 = 77
        int r1 = mc.Calc(5, 6);     // c=4 за замовчуванням => (5+6)*4 = 44
        int r2 = mc.Calc(5);        // b=3, c=4 за замовчуванням => (5+3)*4 = 32
        int r3 = mc.Calc();           // усі за замовчуванням => (2+3)*4 = 20

        Console.WriteLine($"{r0}, {r1}, {r2}, {r3}");
    }
}