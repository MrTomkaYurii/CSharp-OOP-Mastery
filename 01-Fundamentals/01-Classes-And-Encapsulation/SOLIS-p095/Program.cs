// Демонструє передавання посилального типу (клас) та значущого типу (int)
// у метод БЕЗ модифікатора ref, тобто "за значенням".

class MyClass
{
    public int Val = 20; // Ініціалізація поля значенням 20.
}

class Program
{
    static void MyMethod(MyClass f1, int f2)
    {
        // f1 — це копія посилання, але вона вказує на ТОЙ САМИЙ об'єкт, що й a1.
        // Тому зміна поля через f1 буде видима і після повернення з методу.
        f1.Val = f1.Val + 5;    // Додати 5 до поля об'єкта, на який вказує f1.

        // f2 — це окрема копія значення a2. Зміна f2 не впливає на a2.
        f2 = f2 + 5;        // Додати 5 до локальної копії другого параметра.

        Console.WriteLine($"f1.Val: {f1.Val}, f2: {f2}");
    }

    static void Main()
    {
        MyClass a1 = new MyClass();
        int a2 = 10;

        MyMethod(a1, a2);     // Виклик методу.

        // Очікуваний результат: a1.Val: 25 (поле об'єкта змінилося),
        //                       a2: 10    (значуща змінна лишилася незмінною).
        Console.WriteLine($"a1.Val: {a1.Val}, a2: {a2}");
    }
}