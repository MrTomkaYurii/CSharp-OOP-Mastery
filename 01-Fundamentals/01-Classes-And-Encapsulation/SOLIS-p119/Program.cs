// Іменовані аргументи: замість того щоб покладатися на порядок параметрів,
// можна явно вказати ім'я — name: value. Це підвищує читабельність і дозволяє
// передавати аргументи в довільному порядку.

class MyClass
{
    public int Calc(int a, int b, int c)
    {
        return (a + b) * c;
    }

    static void Main()
    {
        MyClass mc = new MyClass();

        int r0 = mc.Calc(4, 3, 2);                    // Лише позиційні аргументи
        int r1 = mc.Calc(4, b: 3, c: 2);              // Позиційні + іменовані (позиційні мають іти першими)
        int r2 = mc.Calc(4, c: 2, b: 3);              // Іменовані можна міняти місцями
        int r3 = mc.Calc(c: 2, b: 3, a: 4);           // Усі аргументи іменовані — порядок довільний
        int r4 = mc.Calc(c: 2, b: 1 + 2, a: 3 + 1);   // Значенням іменованого аргументу може бути вираз

        // Усі виклики дають один результат: (4 + 3) * 2 = 14.
        Console.WriteLine($"{r0}, {r1}, {r2}, {r3}, {r4}");
    }
}
