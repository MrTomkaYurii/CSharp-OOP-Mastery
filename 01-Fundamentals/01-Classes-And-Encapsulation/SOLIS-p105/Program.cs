// Модифікатор out — це "вихідний" параметр: метод ЗОБОВ'ЯЗАНИЙ присвоїти йому значення,
// а початкове значення аргументу не використовується (його можна навіть не ініціалізувати).
// Зручно, коли метод має повернути кілька результатів.

class MyClass
{
    public int Val = 20;             // Ініціалізація поля значенням 20.
}

class Program
{
    static void MyMethod(out MyClass f1, out int f2)
    {
        // Компілятор вимагає присвоїти ОБИДВА out-параметри до виходу з методу.
        f1 = new MyClass();       // Створення об'єкта класу.
        f1.Val = 25;                  // Присвоєння значення полю класу.
        f2 = 15;                  // Присвоєння значення параметру типу int.
    }

    static void Main()
    {
        MyClass a1 = null;   // Початкові значення не важливі — метод їх перезапише.
        int a2;              // Можна навіть лишити без ініціалізації.

        MyMethod(out a1, out a2);   // Виклик методу.
        Console.WriteLine($"a1.Val: {a1.Val}, a2: {a2}");
    }
}