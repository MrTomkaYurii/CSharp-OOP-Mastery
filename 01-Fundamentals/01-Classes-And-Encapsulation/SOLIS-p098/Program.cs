// Те саме, що й попередній приклад, але посилальний параметр передано з ref.
// Для цього прикладу (лише зміна поля, без переприсвоєння) результат такий самий,
// як і без ref — різниця стає помітною лише коли методу переприсвоюють сам параметр.

class MyClass
{
    public int Val = 20; // Ініціалізація поля значенням 20.
}

class Program
{
    static void MyMethod(ref MyClass f1, int f2)
    {
        f1.Val = f1.Val + 5; // Зміна поля об'єкта — видима у викликаючому коді.
        f2 = f2 + 5;     // f2 передано за значенням — зміна локальна.

        Console.WriteLine($"f1.Val: {f1.Val}, f2: {f2}");
    }

    static void Main()
    {
        MyClass a1 = new MyClass();
        int a2 = 10;

        // ref потрібно вказувати і при оголошенні параметра, і при виклику.
        MyMethod(ref a1, a2); // Виклик методу.
        Console.WriteLine($"a1.Val: {a1.Val}, a2: {a2}");
    }
}
