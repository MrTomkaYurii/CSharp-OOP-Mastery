using System;
using System.Threading.Tasks;

namespace AsynchronousProgramming
{
    /// <summary>
    /// =========================================================================================
    /// ПЕРШИЙ КРОК В АСИНХРОННІСТЬ: Task.Delay, неблокуюче очікування та пастка async void
    /// =========================================================================================
    /// Цей проєкт демонструє фундаментальну різницю між Thread.Sleep та Task.Delay:
    /// Task.Delay НЕ блокує потік, а реєструє системний таймер і звільняє потік у пул.
    /// Також тут продемонстровано патерн "Fire-and-Forget" та критичну небезпеку "async void".
    /// 
    /// ТЕОРЕТИЧНІ АСПЕКТИ ТА АРХІТЕКТУРА:
    /// 1. Принцип "There is no thread" під час Task.Delay:
    ///    - Task.Delay(ms) не виділяє окремого фонового потоку для відліку секунд!
    ///    - Він реєструє зворотний виклик (callback) у системній черзі таймерів середовища CLR (TimerQueue).
    ///    - Під час відліку часу фізично працює 0 потоків вашого застосунку.
    ///    - Коли таймер закінчується, годинникове переривання ОС сповіщає CLR, і перший вільний
    ///      потік із пулу ThreadPool підхоплює продовження коду після await.
    /// 2. Пастка "async void" (Fire-and-Forget):
    ///    - Метод із сигнатурою 'async void' неможливо очікувати через await, оскільки він не повертає Task.
    ///    - Якщо всередині 'async void' виникне виняток, його НЕМОЖЛИВО перехопити через try/catch ззовні!
    ///      Виняток потрапляє безпосередньо у SynchronizationContext або ThreadPool і АВАРІЙНО ЗАВЕРШУЄ ВЕСЬ ПРОЦЕС (Crash).
    ///    - Золоте правило: 'async void' дозволено ТІЛЬКИ для обробників подій UI (наприклад, button_Click).
    ///      У будь-якому іншому бізнес-коді завжди використовуйте 'async Task'.
    /// </summary>
    internal class Program
    {
        // =====================================================================================
        // БЛОК 1: Точка входу в програму
        // Запускає асинхронний метод SomeMethod без очікування завершення.
        // =====================================================================================
        public static void Main(string[] args)
        {
            Console.WriteLine("Main Method Started......");

            // Виклик SomeMethod() як Fire-and-Forget.
            // Оскільки метод повертає void, Main не може дізнатися про статус його виконання.
            SomeMethod();

            // Виконується майже миттєво, не чекаючи завершення 10-секундного очікування!
            Console.WriteLine("Main Method End");
            Console.ReadKey();
        }

        // =====================================================================================
        // БЛОК 2: Асинхронний метод верхнього рівня (Fire-and-Forget)
        // Використовує 'async void'. Метод запускає Wait(), не очікуючи його через await.
        // =====================================================================================
        public async static void SomeMethod()
        {
            Console.WriteLine("Some Method Started......");

            // Виклик без 'await': Wait() починає роботу у фоні,
            // а виконання SomeMethod() негайно продовжується до наступного рядка.
            Wait();

            Console.WriteLine("Some Method End");
        }

        // =====================================================================================
        // БЛОК 3: Неблокуюче асинхронне очікування через Task.Delay
        // Task.Delay встановлює таймер на рівні ОС. Потік повертається в пул потоків.
        // Після спрацювання таймера вільний потік з пулу виконує завершальний код.
        // =====================================================================================
        private static async void Wait()
        {
            // await вивільняє потік. Потік не блокується, а обслуговує інші задачі.
            await Task.Delay(TimeSpan.FromSeconds(10));

            // Цей рядок виконується через 10 секунд на потоці з ThreadPool
            Console.WriteLine("\n10 Seconds wait Completed\n");
        }
    }
}
